// Writes tools/<slug>/index.html for every task in src/tasks.ts, and the
// sitemap. Each page is index.html with its own words and a data-task the app
// reads. Run after editing src/tasks.ts or index.html: node scripts/make-task-pages.mjs
// (Node strips the TypeScript types itself.)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { SITE, TASKS, taskPath } from '../src/tasks.ts';

const template = readFileSync('index.html', 'utf8');
const attr = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

const swap = (html, pattern, replacement) => {
  if (!pattern.test(html)) throw new Error(`index.html no longer matches ${pattern}`);
  return html.replace(pattern, replacement);
};

for (const task of TASKS) {
  const url = SITE + taskPath(task);
  let html = template;
  html = swap(html, /<html lang="en">/, `<html lang="en" data-task="${task.slug}">`);
  html = swap(html, /<title>[^<]*<\/title>/, `<title>${attr(task.title)}</title>`);
  html = swap(html, /(<meta name="description" content=")[^"]*(")/, `$1${attr(task.description)}$2`);
  html = swap(html, /(<link rel="canonical" href=")[^"]*(")/, `$1${url}$2`);
  html = swap(html, /(<meta property="og:url" content=")[^"]*(")/, `$1${url}$2`);
  html = swap(html, /(<meta property="og:title" content=")[^"]*(")/, `$1${attr(task.title)}$2`);
  html = swap(html, /(<meta property="og:description" content=")[^"]*(")/, `$1${attr(task.description)}$2`);
  mkdirSync(`tools/${task.slug}`, { recursive: true });
  writeFileSync(
    `tools/${task.slug}/index.html`,
    `<!-- Generated by scripts/make-task-pages.mjs from index.html and src/tasks.ts. -->\n` + html,
  );
}

const urls = ['/', ...TASKS.map(taskPath)]
  .map((path) => `  <url>\n    <loc>${SITE}${path}</loc>\n    <changefreq>monthly</changefreq>\n  </url>`)
  .join('\n');
writeFileSync(
  'public/sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`,
);
console.log(`wrote ${TASKS.length} task pages and public/sitemap.xml`);
